// Exact VA donor VFE packet generator. Gen12 retains MEDIA_OBJECT but removes
// the old hardware-scoreboard DWORDs and defaults to independent EU dispatch.
// Intel media-driver: mhw_render_hwcmd_g12_X.{h,cpp}, mhw_render_g12_X.cpp;
// CompositeState defaults m_FusedEuDispatch=false. No codec/capability changes.
#pragma once
#include "kern_uhd770_page.hpp"
namespace LocalVAVFE {
constexpr size_t PageSize=4096;
constexpr uint64_t FileOffset=0x2c000;
static const uint8_t ReferenceSHA256[]{0x49,0x82,0x09,0x4d,0x4f,0xe0,0xec,0x76,0xe1,0x59,0x17,0x01,0x2e,0x98,0xae,0xe2,0xa9,0x77,0xa2,0x54,0x94,0xfd,0xfd,0x45,0x77,0xbb,0x05,0xdd,0xd5,0xa9,0x5a,0xd8};
struct Patch {unsigned offset,size;uint8_t before[23],after[23];};
static const Patch Patches[]{
 {0x9ae,6,{0x81,0xca,0x00,0x10,0x00,0x00},{0x81,0xca,0x40,0x10,0x00,0x00}},
 {0xa22,6,{0x81,0xc9,0x00,0x10,0x00,0x00},{0x81,0xc9,0x40,0x10,0x00,0x00}},
 {0x9e1,23,{0x83,0xf9,0x02,0x74,0x67,0x83,0xf9,0x01,0x74,0x68,0x85,0xc9,0x75,0x68,0xc7,0x47,0xf8,0x00,0x00,0x00,0x00,0xeb,0x5f},{0xe9,0x71,0x00,0x00,0x00,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90}},
 {0xa47,16,{0x80,0x4f,0xfb,0x80,0xeb,0x0a,0x4c,0x89,0x57,0xf8,0xeb,0x04,0x4c,0x89,0x5f,0xf8},{0x31,0xc9,0x48,0x89,0x4f,0xf8,0x89,0x0f,0x90,0x90,0x90,0x90,0x90,0x90,0x90,0x90}},
};
inline bool matches(const void *data,size_t size,uint64_t offset,bool validated,bool tainted) {
 if(!data || size!=PageSize || offset!=FileOffset || !validated || tainted)return false;
 const auto page=static_cast<const uint8_t *>(data);
 for(const auto &p:Patches)if(memcmp(page+p.offset,p.before,p.size))return false;
 return UHD770Page::matches(page,PageSize,ReferenceSHA256);
}
inline void apply(void *data) {
 auto page=static_cast<uint8_t *>(data);
 for(const auto &p:Patches)memcpy(page+p.offset,p.after,p.size);
}
}
