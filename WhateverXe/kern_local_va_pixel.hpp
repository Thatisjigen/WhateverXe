constexpr unsigned PageCount=sizeof(Pages)/sizeof(Pages[0]);
inline int match(const void *data,size_t size,uint64_t offset,bool validated,bool tainted) {
 if(!data || size!=4096 || !validated || tainted)return -1;
 for(unsigned i=0;i<PageCount;++i) {
  const auto &p=Pages[i];if(offset!=p.offset)continue;
  for(unsigned j=0;j<p.count;++j)
   if(memcmp(static_cast<const uint8_t *>(data)+p.patches[j].offset,p.patches[j].before,p.patches[j].size))return -1;
  return UHD770Page::matches(data,size,p.sha256) ? int(i) : -1;
 }
 return -1;
}
inline void apply(void *data,unsigned index) {
 if(index>=PageCount)return;
 const auto &p=Pages[index];
 for(unsigned j=0;j<p.count;++j)memcpy(static_cast<uint8_t *>(data)+p.patches[j].offset,p.patches[j].after,p.patches[j].size);
}
