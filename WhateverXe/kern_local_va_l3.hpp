// Gen12 media L3 setup. Intel media-driver MhwRenderInterfaceG12::SetL3Cache
// uses RCS L3ALLOCREG (0xb134), default 0xd0000020. The qualified VA helper
// instead emits LRI(register=0,value=0x80000040). Keep the 3-DWORD command size.
#pragma once
#include "kern_uhd770_page.hpp"
namespace LocalVAL3 {
constexpr size_t PageSize=4096;
constexpr uint64_t FileOffset=0x1000;
constexpr unsigned PatchOffset=0xc2a;
static const uint8_t ReferenceSHA256[][32]{{0x93,0x25,0xc6,0xa5,0xed,0x3a,0x93,0xc7,0x1f,0xed,0xd2,0x11,0xd4,0x2e,0xaa,0xbc,0x3e,0x83,0xca,0x78,0x08,0x84,0x62,0x06,0x75,0x2b,0xf7,0x87,0x5d,0x8e,0x85,0x33},{0x12,0x8d,0xeb,0xd8,0xdc,0x38,0xd6,0x0d,0x6d,0xc5,0xa9,0x5e,0xf3,0xb0,0xa3,0x8e,0x8c,0x57,0x8b,0x91,0x71,0x39,0xa0,0x47,0x0a,0xb0,0x8e,0xc8,0xc3,0xa0,0x45,0x3a}};
static const uint8_t Original[]{0x48,0xb8,0,0,0,0,0x40,0,0,0x80};
static const uint8_t Replacement[]{0x48,0xb8,0x34,0xb1,0,0,0x20,0,0,0xd0};
inline bool matches(const void *data,size_t size,uint64_t offset,bool validated,bool tainted) {
 if(!data || size!=PageSize || offset!=FileOffset || !validated || tainted)return false;
 const auto p=static_cast<const uint8_t *>(data);
 if(memcmp(p+PatchOffset,Original,sizeof(Original)))return false;
 for(const auto &digest:ReferenceSHA256)if(UHD770Page::matches(data,size,digest))return true;
 return false;
}
inline void apply(void *data) {memcpy(static_cast<uint8_t *>(data)+PatchOffset,Replacement,sizeof(Replacement));}
}
